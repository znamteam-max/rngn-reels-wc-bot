_MONTH_RE = re.compile(r"^\d{4}-(?:0[1-9]|1[0-2])$")


def _month_title(sheet_name: str) -> str:
    year, month = sheet_name.split("-", 1)
    names = {
        "01": "январь",
        "02": "февраль",
        "03": "март",
        "04": "апрель",
        "05": "май",
        "06": "июнь",
        "07": "июль",
        "08": "август",
        "09": "сентябрь",
        "10": "октябрь",
        "11": "ноябрь",
        "12": "декабрь",
    }
    return f"{names.get(month, month)} {year}"


